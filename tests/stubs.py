"""Пометка для заглушек будущих тестов.

Заглушка пропускается с причиной «ждёт OG-xx». Тело заглушки вызывает
pytest.fail, поэтому если снять пометку и не написать тест, он упадёт.
"""

import pytest

NOT_WRITTEN = "Тест не написан: замените тело перед снятием пометки pending"


def pending(task: str) -> pytest.MarkDecorator:
    """Помечает тест как заглушку, ожидающую задачу.

    Args:
        task: Задача, после которой тест можно написать, например
            "OG-02 (#2)".

    Returns:
        Пометка pytest, пропускающая тест с понятной причиной.
    """
    return pytest.mark.skip(reason=f"Заглушка: ждёт {task}")
